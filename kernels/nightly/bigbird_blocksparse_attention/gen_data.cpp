namespace {

constexpr std::size_t kSequence = 1024;
constexpr std::size_t kBlockSize = 64;
constexpr std::size_t kHeadDim = 8;
constexpr std::size_t kRandomBlocks = 3;
constexpr std::uint32_t kRegionBase[] = {0, 0x20000000U, 0x40000000U,
                                         0x60000000U};

struct Definition {
    std::string name;
    std::string value;
    std::string comment;
};

class Layout {
  public:
    template <typename T>
    void add(const std::string &name, unsigned region,
             const std::vector<T> &values, const std::string &comment) {
        std::vector<std::uint8_t> &blob = blobs_[region];
        blob.resize((blob.size() + 255U) & ~std::size_t{255U}, 0);
        const std::uint32_t address =
            kRegionBase[region] + static_cast<std::uint32_t>(blob.size());
        const std::size_t bytes = values.size() * sizeof(T);
        const std::uint8_t *first =
            reinterpret_cast<const std::uint8_t *>(values.data());
        blob.insert(blob.end(), first, first + bytes);
        define(name + "_ADDR", hex(address) + "u", comment);
        define(name + "_BYTES", std::to_string(bytes) + "u");
    }

    void define(const std::string &name, const std::string &value,
                const std::string &comment = "") {
        definitions_.push_back({name, value, comment});
    }

    void write() const {
        std::filesystem::create_directories("data");
        for (unsigned region = 1; region <= 3; ++region) {
            const auto &blob = blobs_[region];
            std::ofstream output("data/bigbird_blocksparse.region" +
                                     std::to_string(region) + ".bin",
                                 std::ios::binary);
            output.write(reinterpret_cast<const char *>(blob.data()),
                         static_cast<std::streamsize>(blob.size()));
            if (!output)
                throw std::runtime_error("failed to write data blob");
        }
        std::ofstream header("bigbird_blocksparse_data.h");
        header << "// generated by gen_data.cpp; do not edit\n"
                  "#ifndef BIGBIRD_BLOCKSPARSE_DATA_H\n"
                  "#define BIGBIRD_BLOCKSPARSE_DATA_H\n";
        for (const Definition &definition : definitions_) {
            header << "#define " << definition.name << ' '
                   << definition.value;
            if (!definition.comment.empty())
                header << "  // " << definition.comment;
            header << '\n';
        }
        header << "#endif\n";
        if (!header)
            throw std::runtime_error("failed to write generated header");
    }

  private:
    static std::string hex(std::uint32_t value) {
        std::ostringstream stream;
        stream << "0x" << std::hex << std::setw(8) << std::setfill('0')
               << value;
        return stream.str();
    }

    std::vector<std::uint8_t> blobs_[4];
    std::vector<Definition> definitions_;
};

std::uint32_t rng_state = 0x91E10DA5U;

float deterministic_value(float scale) {
    rng_state = rng_state * 1664525U + 1013904223U;
    const float unit = static_cast<float>((rng_state >> 8U) & 0x00FFFFFFU) /
                       static_cast<float>(0x01000000U);
    return scale * (2.0F * unit - 1.0F);
}

std::vector<float> values(std::size_t count, float scale) {
    std::vector<float> result(count);
    for (float &value : result)
        value = deterministic_value(scale);
    return result;
}

double largest_shifted_logit(const bigbird_reference::Graph &graph,
                             const std::vector<float> &query,
                             const std::vector<float> &key) {
    const auto &dims = graph.dims;
    const auto mask = bigbird_reference::build_dense_block_mask(graph);
    const double scale = 1.0 / std::sqrt(static_cast<double>(dims.head_dim));
    double largest = 0.0;
    for (std::size_t q = 0; q < dims.sequence; ++q) {
        double minimum = 1.0e300;
        double maximum = -1.0e300;
        const std::size_t qb = q / dims.block_size;
        for (std::size_t k = 0; k < dims.sequence; ++k) {
            if (!mask[qb * dims.blocks() + k / dims.block_size])
                continue;
            double dot = 0.0;
            for (std::size_t d = 0; d < dims.head_dim; ++d)
                dot += static_cast<double>(query[q * dims.head_dim + d]) *
                       static_cast<double>(key[k * dims.head_dim + d]);
            minimum = std::min(minimum, dot * scale);
            maximum = std::max(maximum, dot * scale);
        }
        largest = std::max(largest, maximum - minimum);
    }
    return largest;
}

} // namespace

int main() {
    const bigbird_reference::Dimensions dims{
        kSequence, kBlockSize, kHeadDim, kRandomBlocks};
    const bigbird_reference::Graph graph =
        bigbird_reference::make_deterministic_graph(dims);
    const bigbird_reference::StructuralStats stats =
        bigbird_reference::validate_graph(graph);
    const std::vector<float> query = values(kSequence * kHeadDim, 0.45F);
    const std::vector<float> key = values(kSequence * kHeadDim, 0.45F);
    const std::vector<float> value = values(kSequence * kHeadDim, 0.60F);
    const double shifted_bound = largest_shifted_logit(graph, query, key);
    if (shifted_bound > 1.2)
        throw std::runtime_error("generated logits exceed polynomial bound");
    const std::vector<float> golden =
        bigbird_reference::attention(graph, query, key, value);
    const std::vector<std::uint8_t> dense_mask =
        bigbird_reference::build_dense_block_mask(graph);
    std::vector<std::uint32_t> golden_masks(dims.blocks());
    for (std::size_t row = 0; row < dims.blocks(); ++row)
        golden_masks[row] =
            bigbird_reference::block_row_bits(dense_mask, dims.blocks(), row);

    std::vector<float> poisoned_output(golden.size());
    std::memset(poisoned_output.data(), 0xEE,
                poisoned_output.size() * sizeof(float));
    std::vector<std::uint32_t> poisoned_masks(dims.blocks(), 0xEEEEEEEEU);
    const std::size_t checks = golden.size() + dims.blocks();
    std::vector<std::uint32_t> poisoned_status(checks, 0xEEEEEEEEU);
    std::vector<std::uint32_t> golden_status(checks, 0U);

    Layout layout;
    layout.define("BBSA_SEQUENCE", std::to_string(kSequence) + "u");
    layout.define("BBSA_BLOCK_SIZE", std::to_string(kBlockSize) + "u");
    layout.define("BBSA_BLOCKS", std::to_string(dims.blocks()) + "u");
    layout.define("BBSA_HEAD_DIM", std::to_string(kHeadDim) + "u");
    layout.define("BBSA_RANDOM_BLOCKS",
                  std::to_string(kRandomBlocks) + "u");
    layout.define("BBSA_OUTPUT_ELEMENTS", std::to_string(golden.size()) + "u");
    layout.define("BBSA_CHECKS", std::to_string(checks) + "u");
    layout.define("BBSA_INV_SQRT_HEAD_DIM", "0.35355339059327376220f");
    layout.add("BBSA_QUERY", 1, query, "FP32 [sequence][head_dim]");
    layout.add("BBSA_KEY", 1, key, "FP32 [sequence][head_dim]");
    layout.add("BBSA_VALUE", 1, value, "FP32 [sequence][head_dim]");
    layout.add("BBSA_RANDOM", 1, graph.random,
               "uint8 [blocks-2][random_blocks]");
    layout.add("BBSA_OUTPUT", 2, poisoned_output,
               "FP32 block-sparse attention result");
    layout.add("BBSA_MASKS", 2, poisoned_masks,
               "uint32 attended-block bits per query block");
    layout.add("BBSA_STATUS", 2, poisoned_status,
               "zero iff each numerical/structural check passes");
    layout.add("BBSA_GOLD_OUTPUT", 3, golden,
               "independent dense-mask double CPU oracle");
    layout.add("BBSA_GOLD_MASKS", 3, golden_masks,
               "exact attended-block bits");
    layout.add("BBSA_GOLD_STATUS", 3, golden_status,
               "all-zero exact status golden");
    layout.write();

    std::cout << "generated sequence=" << kSequence
              << " blocks=" << dims.blocks() << " outputs=" << golden.size()
              << " checks=" << checks << '\n';
    std::cout << "global_rows=" << stats.global_query_rows
              << " local_rows=" << stats.interior_query_rows
              << " random_noncontiguous_edges="
              << stats.noncontiguous_random_edges
              << " max_logit_span=" << shifted_bound << '\n';
    return 0;
}
