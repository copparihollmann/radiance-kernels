namespace {

constexpr std::size_t kSequence = 9;
constexpr std::size_t kKeyDim = 128;
constexpr std::size_t kValueDim = 128;
constexpr std::uint32_t kRegionBase[] = {0U, 0x20000000U, 0x40000000U,
                                         0x60000000U};

struct Definition {
    std::string name;
    std::string value;
    std::string comment;
};

class Layout {
  public:
    template <typename T>
    void add(const std::string &name, unsigned region,
             const std::vector<T> &values, const std::string &comment) {
        std::vector<std::uint8_t> &blob = blobs_[region];
        blob.resize((blob.size() + 255U) & ~std::size_t{255U}, 0U);
        const std::uint32_t address =
            kRegionBase[region] + static_cast<std::uint32_t>(blob.size());
        const std::size_t bytes = values.size() * sizeof(T);
        const std::uint8_t *data =
            reinterpret_cast<const std::uint8_t *>(values.data());
        blob.insert(blob.end(), data, data + bytes);
        define(name + "_ADDR", hex(address) + "u", comment);
        define(name + "_BYTES", std::to_string(bytes) + "u", "");
    }

    void define(const std::string &name, const std::string &value,
                const std::string &comment = "") {
        definitions_.push_back({name, value, comment});
    }

    void write() const {
        std::filesystem::create_directories("data");
        for (unsigned region = 1; region <= 3; ++region) {
            if (blobs_[region].empty())
                continue;
            std::ofstream output("data/qwen35_deltanet_state.region" +
                                     std::to_string(region) + ".bin",
                                 std::ios::binary);
            output.write(reinterpret_cast<const char *>(blobs_[region].data()),
                         static_cast<std::streamsize>(blobs_[region].size()));
            if (!output)
                throw std::runtime_error("failed to write data blob");
        }
        std::ofstream header("qwen35_deltanet_state_data.h");
        header << "// generated by gen_data.cpp; do not edit\n"
                  "#ifndef QWEN35_DELTANET_STATE_DATA_H\n"
                  "#define QWEN35_DELTANET_STATE_DATA_H\n";
        for (const Definition &definition : definitions_) {
            header << "#define " << definition.name << ' ' << definition.value;
            if (!definition.comment.empty())
                header << "  // " << definition.comment;
            header << '\n';
        }
        header << "#endif\n";
        if (!header)
            throw std::runtime_error("failed to write generated header");
    }

  private:
    static std::string hex(std::uint32_t value) {
        std::ostringstream stream;
        stream << "0x" << std::hex << std::setw(8) << std::setfill('0')
               << value;
        return stream.str();
    }

    std::vector<std::uint8_t> blobs_[4];
    std::vector<Definition> definitions_;
};

std::uint32_t rng_state = 0x35D37A11U;

float random_value(float scale, float offset = 0.0F) {
    rng_state = rng_state * 1664525U + 1013904223U;
    const float unit = static_cast<float>((rng_state >> 8U) & 0x00FFFFFFU) /
                       static_cast<float>(0x01000000U);
    return offset + scale * (2.0F * unit - 1.0F);
}

std::vector<float> values(std::size_t count, float scale,
                          float offset = 0.0F) {
    std::vector<float> result(count);
    for (float &value : result)
        value = random_value(scale, offset);
    return result;
}

} // namespace

int main() {
    using namespace qwen35_deltanet_reference;
    const Dimensions dims{/*heads=*/1, /*key_dim=*/kKeyDim,
                          /*value_dim=*/kValueDim};
    Parameters parameters;
    parameters.a_log = {-0.75F};
    parameters.dt_bias = {-0.80F};
    std::vector<TokenInput> tokens(kSequence);
    for (TokenInput &token : tokens) {
        token.q = values(kKeyDim, 0.75F);
        token.k = values(kKeyDim, 0.75F);
        token.v = values(kValueDim, 0.50F);
        token.a = values(1, 0.35F);
        token.b = values(1, 0.80F);
    }
    const std::vector<StepTrace> oracle =
        run_full_sequence(dims, parameters, tokens);

    std::vector<float> q(kSequence * kKeyDim);
    std::vector<float> k(kSequence * kKeyDim);
    std::vector<float> v(kSequence * kValueDim);
    std::vector<float> beta(kSequence);
    std::vector<float> log_decay(kSequence);
    std::vector<float> golden_output(kSequence * kValueDim);
    for (std::size_t time = 0; time < kSequence; ++time) {
        std::memcpy(q.data() + time * kKeyDim, tokens[time].q.data(),
                    kKeyDim * sizeof(float));
        std::memcpy(k.data() + time * kKeyDim, tokens[time].k.data(),
                    kKeyDim * sizeof(float));
        std::memcpy(v.data() + time * kValueDim, tokens[time].v.data(),
                    kValueDim * sizeof(float));
        beta[time] = oracle[time].beta[0];
        log_decay[time] = oracle[time].log_decay[0];
        std::memcpy(golden_output.data() + time * kValueDim,
                    oracle[time].output.data(), kValueDim * sizeof(float));
    }

    // Convert canonical [key][value] oracle state to the device's disjoint
    // per-thread [value][key] column-major layout.
    std::vector<float> golden_state(kKeyDim * kValueDim);
    const std::vector<float> &canonical_state = oracle.back().state;
    for (std::size_t value_index = 0; value_index < kValueDim; ++value_index)
        for (std::size_t key_index = 0; key_index < kKeyDim; ++key_index)
            golden_state[value_index * kKeyDim + key_index] =
                canonical_state[key_index * kValueDim + value_index];

    const std::size_t output_elements = golden_output.size();
    const std::size_t state_elements = golden_state.size();
    std::vector<float> poisoned_output(output_elements);
    std::vector<float> poisoned_state(state_elements);
    std::memset(poisoned_output.data(), 0xEE,
                poisoned_output.size() * sizeof(float));
    std::memset(poisoned_state.data(), 0xEE,
                poisoned_state.size() * sizeof(float));

    const auto gate_bounds =
        std::minmax_element(log_decay.begin(), log_decay.end());
    if (*gate_bounds.first < -0.8F || *gate_bounds.second > 0.0F)
        throw std::runtime_error("generated log-decay exceeds approximation contract");

    Layout layout;
    layout.define("Q35_SEQUENCE", std::to_string(kSequence) + "u");
    layout.define("Q35_KEY_DIM", std::to_string(kKeyDim) + "u");
    layout.define("Q35_VALUE_DIM", std::to_string(kValueDim) + "u");
    layout.define("Q35_OUTPUT_ELEMENTS", std::to_string(output_elements) + "u");
    layout.define("Q35_STATE_ELEMENTS", std::to_string(state_elements) + "u");
    layout.define("Q35_CHECKS",
                  std::to_string(output_elements + state_elements) + "u");
    layout.add("Q35_Q", 1, q, "raw recurrent q [T][K]");
    layout.add("Q35_K", 1, k, "raw recurrent k [T][K]");
    layout.add("Q35_V", 1, v, "recurrent v [T][V]");
    layout.add("Q35_BETA", 1, beta, "sigmoid(b) gate [T]");
    layout.add("Q35_LOG_DECAY", 1, log_decay, "g gate [T]");
    layout.add("Q35_OUTPUT", 2, poisoned_output,
               "poisoned FP32 output [T][V]");
    layout.add("Q35_FINAL_STATE", 2, poisoned_state,
               "poisoned FP32 state [V][K]");
    layout.add("Q35_GOLD_OUTPUT", 3, golden_output,
               "CPU-oracle FP32 output [T][V]");
    layout.add("Q35_GOLD_STATE", 3, golden_state,
               "CPU-oracle FP32 final state [V][K]");
    layout.write();
    std::cout << "generated T=" << kSequence << " K=" << kKeyDim
              << " V=" << kValueDim
              << " checks=" << output_elements + state_elements
              << " log_decay_min=" << *gate_bounds.first
              << " log_decay_max=" << *gate_bounds.second << '\n';
    return 0;
}
