#!/usr/bin/env bash
# Rebuild the accepted dot-1m (stream_dot) configuration at 1, 2 and 4 SM from
# the current HEAD of this repository, which carries 46bc878 ("dot: give each SM
# its own 64-byte line for its reduction partial").
#
# The invocation below is a reconstruction of the one that produced the accepted
# dot-1m artifacts.  It was recovered from, and matches field for field:
#
#   runs/stream-dot-babelstream-f32-1m-bank-blockcyclic2048-candidate-v1/
#       direct-hashed-manifest.json          (recorded build fields)
#   scripts/build-and-gate-dot-bank-blockcyclic-candidate-v1.sh
#       (the gate script that produced those artifacts)
#
#   --elements 1048576        stream_elements: 1048576
#   --loader direct-hashed    loader: "direct-hashed"
#   --warps-per-core 8        muon_warps_per_core: 8
#   --block-cyclic-chunk-elements 2048
#                             dot_block_cyclic_chunk_elements: 2048
#                             dot_block_cyclic_chunk_bytes_per_input: 8192
#   --robust-end-drain        robust_end_drain: true
#   --robust-serial-fence     robust_serial_fence: true
#   --robust-spin-until-reset robust_spin_until_reset: true
#   --robust-post-spin 20000  robust_post_spin: 20000
#
# There is no --full-host-check flag in kernels/stream_dot/run.py; the full host
# check is unconditional in kernels/stream_dot/host.cpp and is recorded as
#   correctness: "exact-device-order-partials-host-final-scalar-and-guards"
#
# Builds only.  No FPGA is touched and no hardware job is launched.
set -euo pipefail

root=/scratch/agustin/radiance-fpga-1a
repo=$root/worktrees/dot1m-linefix-remeasure-v1
out=$root/runs/dot1m-linefix-remeasure-v1/build/direct-hashed
toolchain=$root/toolchains/riscv-tools-prefix/riscv-tools
llvm_muon=$root/src/radiance-kernels/llvm/llvm-muon
build_lock=$root/locks/dot1m-linefix-remeasure-v1-build.lock

mkdir -p "$(dirname "$build_lock")" "$out"
exec 9>"$build_lock"
flock -x 9

cd "$repo"
if [[ -n $(git status --porcelain=v1) ]]; then
  echo "worktree is dirty before build" >&2; exit 1
fi
echo "build revision: $(git rev-parse HEAD)"
git merge-base --is-ancestor 46bc878eb6d063c7942c6fe7c1e53218fed8d052 HEAD \
  || { echo "HEAD does not contain the line-padding fix 46bc878" >&2; exit 1; }

for sms in 1 2 4; do
  dest=$out/stream-dot-babelstream-f32-1m-bank-blockcyclic2048-spin-post20k-linepad--${sms}sm
  if [[ -e $dest/kernel.soc.elf ]]; then
    echo "refusing to overwrite existing ELF: $dest" >&2; exit 1
  fi
  echo "=== building ${sms} SM -> $dest ==="
  # RADIANCE_LIB_PATH points at the primary checkout because lib/libmuonrt.a
  # is a build product that git does not track, so a fresh worktree has no
  # copy of it.  The accepted build used the same path for the same reason.
  # lib/include and lib/linker are byte-identical between the two trees
  # (both clean at HEAD), so this does not change what is compiled.
  LLVM_MUON="$llvm_muon" RADIANCE_LIB_PATH="$root/src/radiance-kernels/lib" \
    RISCV64_TOOLCHAIN_PATH="$toolchain" \
    nice -n 10 python3 -I "$repo/kernels/stream_dot/run.py" \
      --elements 1048576 --sms "$sms" --loader direct-hashed \
      --warps-per-core 8 --block-cyclic-chunk-elements 2048 \
      --robust-end-drain --robust-serial-fence --robust-spin-until-reset \
      --robust-post-spin 20000 \
      --out "$dest" >"$dest.stdout" 2>"$dest.stderr" || {
        echo "build failed for ${sms} SM; see $dest.stderr" >&2; exit 1; }
  # generated/symbols.h is regenerated by the Makefile from the device ELF that
  # was just linked; keep it next to the ELFs as the padding evidence.
  cp -p "$repo/kernels/stream_dot/generated/symbols.h" "$dest/symbols.h"
  cp -p "$repo/kernels/stream_dot/generated/config.h" "$dest/config.h"
  cp -p "$repo/kernels/stream_dot/data.S" "$dest/data.S"
done

python3 -I "$repo/kernels/evaluation/fpga_1a/assemble_manifest.py" \
  --root "$out" --family stream_dot \
  --out "$out/../direct-hashed-manifest.json"
echo "BUILD COMPLETE"
